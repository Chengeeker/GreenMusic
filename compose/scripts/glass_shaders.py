"""Adapt the vendored MIT shader, retaining its optics and single rounded-rectangle SDF."""
from pathlib import Path
import argparse
import re
root=Path(__file__).resolve().parents[2]
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('source',type=Path,nargs='?',default=root/'.local/flutter-1.1.0-archive/packages/liquid_glass_widgets/shaders',help='Directory containing the liquid_glass_widgets 1.13.0 shaders')
source=parser.parse_args().source
out=root/'compose/app/src/main/assets/glass'
out.mkdir(parents=True,exist_ok=True)
license='// Derived from liquid_glass_widgets; Tim Lehmann (2025), Sebastian Degenaar (2026). MIT.\n// Generated by compose/scripts/glass_shaders.py; optical math retained from the Flutter baseline.\n'
def read(name): return (source/name).read_text(encoding='utf-8')
def compact(s):
    s=re.sub(r'/\*.*?\*/','',s,flags=re.S)
    s=re.sub(r'//[^\n]*','',s)
    s=re.sub(r'layout\([^)]*\)\s*','',s)
    return '\n'.join(line for line in s.splitlines() if line.strip() and not line.lstrip().startswith(('#','precision')))
geometry=read('liquid_glass_geometry_blended.frag').replace('#include "displacement_encoding.glsl"',read('displacement_encoding.glsl'))
geometry=geometry.replace('#include "sdf.glsl"','''uniform vec4 uBounds;
float sceneSDF(vec2 p, int n, float k) {
    vec2 b=uBounds.zw/2.0; float r=min(b.x,b.y);
    vec2 q=abs(p-uBounds.xy-b)-b+r;
    return min(max(q.x,q.y),0.0)+length(max(q,0.0))-r;
}''')
geometry=re.sub(r'uniform float uShapeData\[.*?\];','',geometry)
geometry=geometry.replace('smoothstep(smoothing * 0.5, -smoothing * 0.5, sdN)', '(1.0 - smoothstep(-smoothing * 0.5, smoothing * 0.5, sdN))')
render=read('liquid_glass_render.frag').replace('#include "displacement_encoding.glsl"',read('displacement_encoding.glsl')).replace('#include "render.glsl"',read('render.glsl'))
# Android owns the texture orientation. Strip inactive Flutter branches, not just directives.
render, branches = re.subn(r'^\s*#(?:ifdef LGR_GLES_FLIP_SAMPLE_Y|if DEBUG_GEOMETRY)\s*\n.*?^\s*#endif[^\n]*', '', render, flags=re.M | re.S)
assert branches == 5 and not re.search(r'^\s*#(?:if|else|elif|endif)\b', render, re.M)
# Geometry uses a padded texture, but pinch and the refraction limit use the pill bounds.
render=render.replace('uniform vec2 uGeometrySize;', 'uniform vec2 uGeometrySize;\nuniform vec4 uBounds;')
render=render.replace('min(uGeometrySize.x, uGeometrySize.y)', 'min(uBounds.z, uBounds.w)')
render=render.replace('geometryUV - vec2(0.5)', '(fragCoord - uBounds.xy) / uBounds.zw - vec2(0.5)')
render=render.replace('smoothstep(touchRadius, 0.0, touchDist)', '(1.0 - smoothstep(0.0, touchRadius, touchDist))')
for name,s in [('geometry',geometry),('render',render)]:
    s=compact(s)
    gles=s.replace('FlutterFragCoord().xy','vec2(gl_FragCoord.x,uSize.y-gl_FragCoord.y)')
    # Bitmap upload is top-first. Only the geometry FBO is stored bottom-first.
    gles=gles.replace('texture(uGeometryTexture, geometryUV)', 'texture(uGeometryTexture, vec2(geometryUV.x, 1.0 - geometryUV.y))')
    (out/(name+'.glsl')).write_text('#version 300 es\nprecision highp float;\n'+license+gles,encoding='utf-8')
    s=re.sub(r'out vec4 fragColor;','',s)
    s=s.replace('uniform sampler2D','uniform shader')
    s=s.replace('texture(uBackgroundTexture,','sampleBackground(').replace('texture(uGeometryTexture,','sampleGeometry(')
    s=s.replace('void main() {','half4 main(float2 pixelCoord) {\nvec4 fragColor;').replace('FlutterFragCoord().xy','pixelCoord').replace('return;','return half4(fragColor);')
    s=s.rstrip()[:-1]+'return half4(fragColor);\n}'
    if name=='render':
        position=s.index('uniform shader uGeometryTexture;')+len('uniform shader uGeometryTexture;')
        s=s[:position]+'''\nvec4 sampleBackground(vec2 uv) { return uBackgroundTexture.eval(uv*uSize); }
vec4 sampleGeometry(vec2 uv) { return uGeometryTexture.eval(uv*uGeometrySize); }\n'''+s[position:]
    for i in (2,3,4): s=re.sub(r'\bvec'+str(i)+r'\b','float'+str(i),s)
    (out/(name+'.agsl')).write_text(license+s,encoding='utf-8')
